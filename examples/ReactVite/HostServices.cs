using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Text.Json.Serialization;
using System.Threading.Channels;
using Kumiko.Runtime;
using Kumiko.Web;

namespace ReactVite;

public sealed record NoArguments;
public sealed record AddRequest(int By);
public sealed record HostInfo(string Platform, string Runtime, string Mode);

[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
[JsonSerializable(typeof(NoArguments))]
[JsonSerializable(typeof(AddRequest))]
[JsonSerializable(typeof(HostInfo))]
[JsonSerializable(typeof(int))]
internal partial class HostJson : JsonSerializerContext;

/// <summary>The typed contract React imports from web/src/kumiko/client.js.</summary>
static class HostServices
{
    const string Empty = "Record<string, never>";

    public static void Register(ServiceRegistry services, Program<CounterModel, CounterMsg> program, CounterFeed feed, string mode)
    {
        services.Bind("Host", "info", (NoArguments _) => new HostInfo(RuntimeInformation.OSDescription, RuntimeInformation.FrameworkDescription, mode),
            HostJson.Default.NoArguments, HostJson.Default.HostInfo, Empty,
            "{ platform: string; runtime: string; mode: \"bundled\" | \"dev-server\" }");
        // Unary handlers start on the UI thread, so the update can run before the reply is sent.
        services.Bind("Host", "add", (AddRequest request) =>
        {
            program.Send(new CounterMsg.Add(request.By, "React"));
            program.ProcessMessages();
            return program.Model.Count;
        }, HostJson.Default.AddRequest, HostJson.Default.Int32, "{ by: number }", "number");
        services.BindStream("Host", "watch", (CallContext context, NoArguments _) => feed.Watch(context.CancellationToken),
            HostJson.Default.NoArguments, HostJson.Default.Int32, Empty, "number");
    }

    /// <summary>Generates the checked-in client without a window or browser.</summary>
    public static (string JavaScript, string TypeScript) Client()
    {
        var services = new ServiceRegistry();
        using var program = CounterApp.CreateProgram();
        Register(services, program, new(), "bundled");
        return ("// Generated by Kumiko from ReactVite/HostServices.cs. Regenerate with --write-client.\n" + services.JavaScript(), services.TypeScript());
    }
}

/// <summary>Fans the latest count out to every open React stream. Each watcher keeps only its newest value.</summary>
sealed class CounterFeed
{
    readonly Lock gate = new();
    readonly List<Channel<int>> watchers = [];
    int latest;

    public void Publish(int count)
    {
        lock (gate)
        {
            if (count == latest)
                return;
            latest = count;
            foreach (var watcher in watchers)
                watcher.Writer.TryWrite(count);
        }
    }

    public async IAsyncEnumerable<int> Watch([EnumeratorCancellation] CancellationToken token)
    {
        var channel = Channel.CreateBounded<int>(new BoundedChannelOptions(1)
        {
            FullMode = BoundedChannelFullMode.DropOldest,
            SingleReader = true
        });
        lock (gate)
        {
            watchers.Add(channel);
            channel.Writer.TryWrite(latest);
        }
        try
        {
            await foreach (int count in channel.Reader.ReadAllAsync(token))
                yield return count;
        }
        finally
        {
            lock (gate)
                watchers.Remove(channel);
        }
    }
}
