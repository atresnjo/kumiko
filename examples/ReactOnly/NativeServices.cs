using System.Text.Json.Serialization;
using Kumiko;
using Kumiko.Desktop;
using Kumiko.Web;

namespace ReactOnly;

public sealed record NoArguments;
public sealed record NativeInfo(string Platform, string Os, bool Dark);
public sealed record TextFile(string Path, string Text);
public sealed record SaveRequest(string Name, string Text);
public sealed record TextRequest(string Text);
public sealed record NotifyRequest(string Title, string Body);
public sealed record PathRequest(string Path);

[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
[JsonSerializable(typeof(NoArguments))]
[JsonSerializable(typeof(NativeInfo))]
[JsonSerializable(typeof(TextFile))]
[JsonSerializable(typeof(SaveRequest))]
[JsonSerializable(typeof(TextRequest))]
[JsonSerializable(typeof(NotifyRequest))]
[JsonSerializable(typeof(PathRequest))]
[JsonSerializable(typeof(string))]
[JsonSerializable(typeof(bool))]
internal partial class NativeJson : JsonSerializerContext;

/// <summary>The native features the React app may use, and nothing else. Generated client: web/src/kumiko/client.js.</summary>
static class NativeServices
{
    const string Empty = "Record<string, never>";
    const int MaxFileBytes = 1024 * 1024;
    public static readonly NanoEvent<bool> Appearance = new("appearance", NativeJson.Default.Boolean, "boolean");

    public static void Register(App app) => Register(app.Services);

    static void Register(ServiceRegistry services)
    {
        var json = NativeJson.Default;
        services.Bind("Native", "info", static (NoArguments _) => new NativeInfo(Platform(), System.Runtime.InteropServices.RuntimeInformation.OSDescription,
            Kumiko.Desktop.Appearance.IsDark), json.NoArguments, json.NativeInfo, Empty,
            "{ platform: \"macos\" | \"windows\" | \"linux\"; os: string; dark: boolean }");
        services.BindAsync("Native", "openText", static (CallContext context, NoArguments _) => OnUiThread(context, OpenText),
            json.NoArguments, json.TextFile, Empty, "{ path: string; text: string } | null");
        services.BindAsync("Native", "saveText", static (CallContext context, SaveRequest request) => OnUiThread(context, () => SaveText(request)),
            json.SaveRequest, json.String, "{ name: string; text: string }", "string | null");
        services.Bind("Native", "copyText", static (TextRequest request) =>
        {
            Clipboard.WriteText(request.Text);
            return true;
        }, json.TextRequest, json.Boolean, "{ text: string }", "boolean");
        services.Bind("Native", "readText", static (NoArguments _) => Clipboard.ReadText(), json.NoArguments, json.String, Empty, "string");
        services.BindAsync("Native", "notify", static async (CallContext context, NotifyRequest request) =>
        {
            await Notifications(context).Show(new("react-only-" + Guid.NewGuid().ToString("N"), request.Title, request.Body));
            return true;
        }, json.NotifyRequest, json.Boolean, "{ title: string; body: string }", "boolean");
        services.Bind("Native", "reveal", static (PathRequest request) =>
        {
            Shell.Reveal(request.Path);
            return true;
        }, json.PathRequest, json.Boolean, "{ path: string }", "boolean");
        services.RegisterEvent(Appearance);
    }

    /// <summary>Generates the checked-in client without a window or browser.</summary>
    public static (string JavaScript, string TypeScript) Client()
    {
        var services = new ServiceRegistry();
        Register(services);
        return ("// Generated by Kumiko from ReactOnly/NativeServices.cs. Regenerate with --write-client.\n" + services.JavaScript(), services.TypeScript());
    }

    static string Platform() => OperatingSystem.IsMacOS() ? "macos" : OperatingSystem.IsWindows() ? "windows" : "linux";

    static TextFile? OpenText()
    {
        if (Dialogs.Open(new(Title: "Open text file", Extensions: ["txt", "md", "json", "csv"])) is not [var path])
            return null;
        if (new FileInfo(path).Length > MaxFileBytes)
            throw new InvalidOperationException("This example opens text files up to 1 MiB.");
        return new(path, File.ReadAllText(path));
    }

    static string? SaveText(SaveRequest request)
    {
        if (Dialogs.Save(new(Title: "Save text file", Name: request.Name, Extensions: ["txt", "md"])) is not { } path)
            return null;
        File.WriteAllText(path, request.Text);
        return path;
    }

    static Notification? notifications;
    static Notification Notifications(CallContext context) => notifications ??= new(context.Window!.App);

    // Modal panels run from the main loop after the bridge callback returns, not inside it.
    static ValueTask<T> OnUiThread<T>(CallContext context, Func<T> work)
    {
        var result = new TaskCompletionSource<T>(TaskCreationOptions.RunContinuationsAsynchronously);
        context.Window!.App.Dispatch(() =>
        {
            try
            {
                result.SetResult(work());
            }
            catch (Exception error)
            {
                result.SetException(error);
            }
        });
        return new(result.Task);
    }
}
