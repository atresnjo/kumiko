using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization.Metadata;
using System.Text.RegularExpressions;

namespace Kumiko.Web;

public readonly record struct CallContext(Window? Window, CancellationToken CancellationToken = default);
public sealed partial class ServiceRegistry
{
    sealed record Method(
        string Service,
        string Name,
        string ArgumentType,
        string ResultType,
        Func<CallContext, JsonElement, ValueTask<string>> Invoke
    );
    readonly Dictionary<string, Method> methods = new(StringComparer.Ordinal);
    readonly Dictionary<string, string> events = new(StringComparer.Ordinal);
    [GeneratedRegex("^[A-Za-z_$][A-Za-z0-9_$]*$", RegexOptions.CultureInvariant)]
    private static partial Regex Identifier();
    static void Validate(string value)
    {
        if (!Identifier().IsMatch(value))
            throw new ArgumentException("Expected a JavaScript identifier.", nameof(value));
    }

    public void Bind<TArgument, TResult>(
        string service,
        string method,
        Func<TArgument, TResult> handler,
        JsonTypeInfo<TArgument> arguments,
        JsonTypeInfo<TResult> result,
        string argumentType,
        string resultType
    ) => BindAsync(
        service,
        method,
        (ctx, arg) => ValueTask.FromResult(handler(arg)),
        arguments,
        result,
        argumentType,
        resultType
    );
    public void BindAsync<TArgument, TResult>(
        string service,
        string method,
        Func<CallContext, TArgument, ValueTask<TResult>> handler,
        JsonTypeInfo<TArgument> arguments,
        JsonTypeInfo<TResult> result,
        string argumentType,
        string resultType
    )
    {
        Validate(service);
        Validate(method);
        if (streams.ContainsKey(service + "." + method))
            throw new ArgumentException("IPC stream already registered.", nameof(method));
        methods.Add(service + "." + method, new(service, method, argumentType, resultType, async (ctx, arg) =>
        {
            TArgument input = arg.Deserialize(arguments) ?? throw new JsonException("Missing argument.");
            var value = await handler(ctx, input);
            return JsonSerializer.Serialize(value, result);
        }));
    }

    public void RegisterEvent<T>(NanoEvent<T> definition)
    {
        Validate(definition.ClientName);
        events.Add(definition.Name, definition.TypeScriptType);
    }

    public string Invoke(string method, JsonElement argument) => InvokeAsync(method, argument, default).AsTask().GetAwaiter().GetResult();
    public ValueTask<string> InvokeAsync(
        string method,
        JsonElement argument,
        CallContext context
    ) => methods.TryGetValue(method, out var descriptor) ? descriptor.Invoke(context, argument) : throw new KeyNotFoundException($"Unknown IPC method: {method}");
    public string JavaScript()
    {
        var text = new StringBuilder("export const kumiko=window.kumiko;\n");
        foreach (var group in methods.Values.Select(m => m.Service).Concat(streams.Values.Select(m => m.Service)).Distinct(StringComparer.Ordinal))
        {
            text.Append("export const ").Append(group).Append("=Object.freeze({\n");
            foreach (var method in methods.Values.Where(m => m.Service == group))
                text.Append(method.Name)
                    .Append(":(argument)=>window.kumiko.call(")
                    .Append(JsonSerializer.Serialize(group + "." + method.Name, WebJson.Default.String))
                    .Append(",argument),\n");
            foreach (var method in streams.Values.Where(m => m.Service == group))
                text.Append(method.Name).Append(":(argument)=>window.kumiko.stream(")
                    .Append(JsonSerializer.Serialize(group + "." + method.Name, WebJson.Default.String)).Append(",argument),\n");
            text.Append("});\n");
        }

        foreach (var e in events)
            text.Append("export const on")
                .Append(Pascal(e.Key))
                .Append("=(fn)=>window.kumiko.on(")
                .Append(JsonSerializer.Serialize(e.Key, WebJson.Default.String))
                .Append(",fn);\n");
        return text.ToString();
    }

    public string TypeScript()
    {
        var text = new StringBuilder("// Generated by Kumiko from explicitly registered C# contracts.\n");
        foreach (var group in methods.Values.Select(m => m.Service).Concat(streams.Values.Select(m => m.Service)).Distinct(StringComparer.Ordinal))
        {
            text.Append("export declare const ").Append(group).Append(": {\n");
            foreach (var m in methods.Values.Where(m => m.Service == group))
                text.Append("  ")
                    .Append(m.Name)
                    .Append("(argument: ")
                    .Append(m.ArgumentType)
                    .Append("): Promise<")
                    .Append(m.ResultType)
                    .Append(">;\n");
            foreach (var m in streams.Values.Where(m => m.Service == group))
                text.Append("  ").Append(m.Name).Append("(argument: ").Append(m.ArgumentType).Append("): AsyncIterable<").Append(m.ItemType).Append(">;\n");
            text.Append("};\n");
        }

        foreach (var e in events)
            text.Append("export declare function on")
                .Append(Pascal(e.Key))
                .Append("(listener: (payload: ")
                .Append(e.Value)
                .Append(") => void): () => void;\n");
        return text.ToString();
    }

    internal static string Pascal(string value) => string.Concat(value.Split(['-', '_', ':', '.'], StringSplitOptions.RemoveEmptyEntries)
        .Select(s => char.ToUpperInvariant(s[0]) + s[1..]));
}

public sealed class NanoEvent<T>(string name, JsonTypeInfo<T> typeInfo, string typeScriptType)
{
    public string Name { get; } = name;
    public string ClientName => "on" + ServiceRegistry.Pascal(Name);
    public string TypeScriptType { get; } = typeScriptType;

    public void Emit(Window window, T payload)
    {
        var json = "{\"t\":\"event\",\"n\":" + JsonSerializer.Serialize(Name, WebJson.Default.String) + ",\"p\":" + JsonSerializer.Serialize(payload, typeInfo) + "}";
        var page = window.Page;
        if (page is null)
            return;
        long generation = page.EventGeneration;
        window.App.Dispatch(() => page.EnqueueEvent(json, generation));
    }

    public void Broadcast(App app, T payload)
    {
        foreach (var window in app.Windows)
            Emit(window, payload);
    }
}
