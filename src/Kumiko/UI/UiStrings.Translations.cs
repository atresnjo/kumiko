    /// <summary>
    /// The built-in text for <paramref name="culture"/> or its nearest parent language, else English.
    /// Applications can start from it and replace individual strings with <c>with</c>.
    /// </summary>
    public static UiStrings For(CultureInfo culture)
    {
        ArgumentNullException.ThrowIfNull(culture);
        for (var current = culture; !string.IsNullOrEmpty(current.Name); current = current.Parent)
        {
            if (Translations.TryGetValue(current.Name, out var strings))
                return strings;
            if (current.Name == "zh")
                return Translations["zh-Hans"];
        }
        return English;
    }

