using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Kumiko.Analyzers;

// Runs before CoreCompile: SDK generators cannot consume another generator's output.
// Emitting declarations as compiler inputs lets System.Text.Json generate NativeAOT metadata.
static partial class Generate
{
    static int Main(string[] args)
    {
        if (args.Length != 3)
            return 1;
        var sources = File.ReadAllLines(args[0]).Where(File.Exists).Distinct().Select(p => CSharpSyntaxTree.ParseText(File.ReadAllText(p), path: p)).ToArray();
        var references = File.ReadAllLines(args[1]).Where(File.Exists).Distinct().Select(p => MetadataReference.CreateFromFile(p));
        var compilation = CSharpCompilation.Create("Kumiko.Runtime.Generation", sources, references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        var output = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        var routes = Routes(compilation);
        if (routes is null)
            return 1;
        output.Append(routes);
        // Resolve generated route kinds/dispatch before discovering app models and JSON metadata.
        compilation = compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText(routes));
        var guards = Guards(compilation);
        if (guards is null)
            return 1;
        output.Append(guards);
        compilation = compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText(guards));
        var unions = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var tree in sources)
        {
            var model = compilation.GetSemanticModel(tree);
            foreach (var declaration in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>().Where(t => t.BaseList is not null))
            {
                if (model.GetDeclaredSymbol(declaration) is not INamedTypeSymbol app)
                    continue;
                if (KumikoAnalyzer.ViewContract(app) is { } viewContract && viewContract.TypeArguments[1] is INamedTypeSymbol viewMessages)
                    unions.Add(viewMessages);
                // A component's messages are recorded inside its parent's, so they need the same union metadata.
                foreach (var component in app.Interfaces.Where(i => i.Name == "IKumikoComponent" && i.ContainingNamespace.ToDisplayString() == "Kumiko.Runtime"))
                    if (component.TypeArguments[1] is INamedTypeSymbol { TypeKind: not TypeKind.TypeParameter } messages)
                        unions.Add(messages);
                var contract = app.Interfaces.FirstOrDefault(i => i.Name == "IKumiko" && i.TypeArguments.Length == 2 && i.ContainingNamespace.ToDisplayString() == "Kumiko.Runtime");
                if (contract is null)
                    continue;
                if (declaration is not ClassDeclarationSyntax || app.ContainingType is not null || app.Arity != 0 || !declaration.Modifiers.Any(SyntaxKind.PartialKeyword))
                {
                    Console.Error.WriteLine($"{tree.FilePath}: error KUM011: Kumiko apps must be top-level, non-generic partial classes.");
                    return 1;
                }
                var state = contract.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var message = contract.TypeArguments[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var ns = app.ContainingNamespace.IsGlobalNamespace ? null : app.ContainingNamespace.ToDisplayString();
                if (ns is not null)
                    output.AppendLine($"namespace {ns} {{");
                var subscriptions = app.GetMembers("Subscriptions").OfType<IMethodSymbol>().Any() ? "Subscriptions" : "null";
                if (app.GetMembers("View").OfType<IMethodSymbol>().Any())
                {
                    Console.Error.WriteLine($"{tree.FilePath}: error KUM011: Static application views are unsupported. Declare a NavigationRoot with sealed Screen<Props, Message> destinations.");
                    return 1;
                }
                var windowContract = app.AllInterfaces.FirstOrDefault(i => i.Name == "IKumikoWindows" && i.ContainingNamespace.ToDisplayString() == "Kumiko.Runtime");
                var windowType = windowContract?.TypeArguments[2];
                var windowName = windowType?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                // Root selection is ordinary C#; no matching-type discovery or public render adapter.
                var rootAdapter = windowName is null ? "" : $$"""
                    public static global::Kumiko.Runtime.NavigationRoot<{{message}}> Root({{state}} model)
                    {
                        var first = global::System.Linq.Enumerable.FirstOrDefault(Windows(model));
                        return first is null ? throw new global::System.InvalidOperationException("No window root is open.") : WindowRoot(model, first.Id);
                    }
                    """;
                var configureWindows = windowName is null ? "" : $".WithWindows(Windows, WindowRoot, {app.Name}KumikoJson.Default.Window)";
                var windowMetadata = windowName is null ? "" : $"[global::System.Text.Json.Serialization.JsonSerializable(typeof({windowName}), TypeInfoPropertyName = \"Window\")]";
                output.AppendLine($$"""
                    partial class {{app.Name}}
                    {
                        {{rootAdapter}}
                        public static global::Kumiko.Runtime.Program<{{state}}, {{message}}> CreateProgram() => CreateProgram(Init);
                        public static global::Kumiko.Runtime.Program<{{state}}, {{message}}> CreateProgram({{state}} initial) => CreateProgram(initial, new global::Kumiko.Runtime.KumikoServices());
                        public static global::Kumiko.Runtime.Program<{{state}}, {{message}}> CreateProgram(global::Kumiko.Runtime.KumikoServices services) => CreateProgram(Init, services);
                        public static global::Kumiko.Runtime.Program<{{state}}, {{message}}> CreateProgram({{state}} initial, global::Kumiko.Runtime.KumikoServices services) =>
                            new global::Kumiko.Runtime.Program<{{state}}, {{message}}>(initial, Update, Root, {{app.Name}}KumikoJson.Default.Model, {{app.Name}}KumikoJson.Default.Message, {{subscriptions}}, services.Validate({{RequiredServices(compilation, app)}})){{configureWindows}};
                        public static global::Kumiko.Runtime.Program<{{state}}, {{message}}> CreateProgram(global::System.IServiceProvider provider) => CreateProgram(Init, provider);
                        public static global::Kumiko.Runtime.Program<{{state}}, {{message}}> CreateProgram({{state}} initial, global::System.IServiceProvider provider) =>
                            CreateProgram(initial, global::Kumiko.Runtime.KumikoServices.From(provider));
                        public static global::Kumiko.Runtime.IProgram Create() => CreateProgram();
                    }
                    {{windowMetadata}}
                    {{DistinctNames(compilation, windowType is null ? [contract.TypeArguments[0], contract.TypeArguments[1]] : [contract.TypeArguments[0], contract.TypeArguments[1], windowType])}}[global::System.Text.Json.Serialization.JsonSerializable(typeof({{state}}), TypeInfoPropertyName = "Model")]
                    [global::System.Text.Json.Serialization.JsonSerializable(typeof({{message}}), TypeInfoPropertyName = "Message")]
                    internal partial class {{app.Name}}KumikoJson : global::System.Text.Json.Serialization.JsonSerializerContext;
                    """);
                if (ns is not null)
                    output.AppendLine("}");
                if (windowType is INamedTypeSymbol windowUnion)
                    unions.Add(windowUnion);
                if (contract.TypeArguments[1] is INamedTypeSymbol union)
                    unions.Add(union);
            }
        }
        foreach (var union in unions)
        {
            if (!union.IsAbstract || !union.Locations.Any(l => l.IsInSource))
                continue;
            if (union.GetAttributes().Any(a => a.AttributeClass?.Name is "JsonPolymorphicAttribute" or "JsonDerivedTypeAttribute"))
            {
                Console.Error.WriteLine($"{union.Locations.FirstOrDefault()}: error KUM011: Remove manual message union attributes; Kumiko generates the complete variant list.");
                return 1;
            }
            var declaration = union.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() as RecordDeclarationSyntax;
            if (declaration is null || union.Arity != 0 || !declaration.Modifiers.Any(SyntaxKind.PartialKeyword) || union.ContainingType is not null)
            {
                Console.Error.WriteLine($"{union.Locations.FirstOrDefault()}: error KUM011: Abstract Kumiko messages must be top-level partial records for generated union metadata.");
                return 1;
            }
            if (!union.ContainingNamespace.IsGlobalNamespace)
                output.AppendLine($"namespace {union.ContainingNamespace.ToDisplayString()} {{");
            output.AppendLine("[global::System.Text.Json.Serialization.JsonPolymorphic(TypeDiscriminatorPropertyName = \"type\")]");
            foreach (var type in Types(compilation.Assembly.GlobalNamespace).Where(t => !t.IsAbstract && Derives(t, union)).OrderBy(t => t.ToDisplayString(), StringComparer.Ordinal))
                output.AppendLine($"[global::System.Text.Json.Serialization.JsonDerivedType(typeof({type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}), \"{type.ToDisplayString()}\")]");
            output.AppendLine($"abstract partial record {union.Name};");
            if (!union.ContainingNamespace.IsGlobalNamespace)
                output.AppendLine("}");
        }
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[2]))!);
        var text = output.ToString();
        if (!File.Exists(args[2]) || File.ReadAllText(args[2]) != text)
            File.WriteAllText(args[2], text);
        return 0;
    }

    static bool Derives(INamedTypeSymbol type, INamedTypeSymbol parent)
    {
        for (var next = type.BaseType; next is not null; next = next.BaseType)
            if (SymbolEqualityComparer.Default.Equals(next, parent))
                return true;
        return false;
    }

    static IEnumerable<INamedTypeSymbol> Types(INamespaceOrTypeSymbol parent)
    {
        foreach (var member in parent.GetMembers())
        {
            if (member is INamedTypeSymbol type)
                yield return type;
            if (member is INamespaceOrTypeSymbol nested)
                foreach (var child in Types(nested))
                    yield return child;
        }
    }
}
